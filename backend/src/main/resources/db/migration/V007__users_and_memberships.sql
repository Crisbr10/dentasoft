-- Users and their memberships of clinics (M02-T03, ADR 0015).
--
-- Runs as dentasoft_owner. Every transaction of a signed-in user passes the user to PostgreSQL as app.user_id
-- (set_config(…, true), like app.tenant_id): the Keycloak user ID, the `sub` of the validated access token. Processes
-- without a user (jobs, asynchronous listeners) leave it unset, so the policies below let them see nothing.
--
-- To undo it by hand, as the owner: DROP POLICY member_select ON clinic; DROP TABLE clinic_membership, user_account;
-- DROP FUNCTION enable_user_isolation(text, text);

-- Like enable_tenant_isolation (V001), for a table whose rows belong to one user instead of one clinic: Row Level
-- Security enabled and forced, and a `user_isolation` policy that only lets through rows whose p_column equals
-- app.user_id. Fails closed in the same way: without a user the setting is NULL or '' and no row matches; an INSERT
-- raises 42501. Only migrations call it.
CREATE FUNCTION enable_user_isolation(p_table text, p_column text)
    RETURNS void
    LANGUAGE plpgsql
    SET search_path = pg_catalog, pg_temp
AS
$$
BEGIN
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', p_table);
    EXECUTE format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY', p_table);
    EXECUTE format(
            'CREATE POLICY user_isolation ON public.%I FOR ALL'
                || ' USING (%I = NULLIF(current_setting(''app.user_id'', true), '''')::uuid)'
                || ' WITH CHECK (%I = NULLIF(current_setting(''app.user_id'', true), '''')::uuid)',
            p_table, p_column, p_column);
END;
$$;

REVOKE EXECUTE ON FUNCTION enable_user_isolation(text, text) FROM PUBLIC, dentasoft_app;

-- A person who signs in to Dentasoft, whatever their clinics. Keycloak owns their personal data (name, email,
-- phone): nothing of it is copied here, and the frontend reads it from the ID token. The id is the Keycloak user ID
-- (`sub`), not a UUID v7 generated by the application: it is what the audit columns and audit_log.actor_id already
-- hold, and it is known from the token without a lookup.
-- Not a clinic's row, so it has no tenant_id: each user only sees and creates their own row.
CREATE TABLE user_account
(
    id         uuid PRIMARY KEY,
    status     varchar(20) NOT NULL DEFAULT 'ACTIVE',
    created_at timestamptz NOT NULL,
    created_by uuid,
    updated_at timestamptz NOT NULL,
    updated_by uuid,
    version    bigint      NOT NULL DEFAULT 0,
    CONSTRAINT user_account_status_check CHECK (status IN ('ACTIVE', 'DISABLED'))
);

SELECT enable_user_isolation('user_account', 'id');

-- The application only registers users on their first access (INSERT … ON CONFLICT DO NOTHING) and reads them.
-- Nothing changes a user's status yet, so not even a bug can disable or reactivate one.
REVOKE UPDATE ON user_account FROM dentasoft_app;

-- What a user is in a clinic: one role per clinic (FHIR PractitionerRole). The roles come from this table, never from
-- the token or from Keycloak's organizations (ADR 0015). Never deleted: a membership that ends is made inactive, so
-- the audit log keeps pointing at it.
CREATE TABLE clinic_membership
(
    id         uuid PRIMARY KEY,
    tenant_id  uuid        NOT NULL REFERENCES clinic (id),
    -- Whether an invitation may create a membership for a user that has never signed in (and so has no
    -- user_account row yet) is decided by M02-T05.
    user_id    uuid        NOT NULL REFERENCES user_account (id),
    role       varchar(20) NOT NULL,
    active     boolean     NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL,
    created_by uuid,
    updated_at timestamptz NOT NULL,
    updated_by uuid,
    version    bigint      NOT NULL DEFAULT 0,
    -- The clinic roles of docs/plan/configuracion.md. PLATFORM_ADMIN is not one: it is a realm role of the token.
    CONSTRAINT clinic_membership_role_check
        CHECK (role IN ('ADMIN_CLINICA', 'ODONTOLOGO', 'HIGIENISTA', 'RECEPCION', 'FACTURACION')),
    -- One role per clinic.
    CONSTRAINT clinic_membership_tenant_id_user_id_key UNIQUE (tenant_id, user_id)
);

-- The policies own_memberships and member_select look memberships up by user on every read, without a clinic.
CREATE INDEX clinic_membership_user_id_idx ON clinic_membership (user_id);

SELECT enable_tenant_isolation('clinic_membership');

-- A user's own memberships, in every clinic, before there is an active clinic: what GET /api/v1/me lists and what
-- M02-T04 checks to accept a clinic. PostgreSQL ORs it with tenant_isolation, so the application sees the memberships
-- of the active clinic (managing its users, M02-T05) plus the user's own in other clinics. SELECT only: inserts and
-- updates still need tenant_isolation, so a membership is only ever created or changed in the active clinic, and no
-- one can add themselves to, or reactivate themselves in, another clinic.
CREATE POLICY own_memberships ON clinic_membership FOR SELECT TO dentasoft_app
    USING (user_id = NULLIF(current_setting('app.user_id', true), '')::uuid);

-- The clinics in which the user has an active membership, also without an active clinic, so GET /api/v1/me can show
-- their names and whether they are suspended. The subquery is itself under the Row Level Security of
-- clinic_membership, which only adds the user's own rows. A membership made inactive stops granting it at once.
CREATE POLICY member_select ON clinic FOR SELECT TO dentasoft_app
    USING (EXISTS (SELECT 1
                   FROM clinic_membership m
                   WHERE m.tenant_id = clinic.id
                     AND m.user_id = NULLIF(current_setting('app.user_id', true), '')::uuid
                     AND m.active));
